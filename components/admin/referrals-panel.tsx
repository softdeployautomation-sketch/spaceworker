"use client";

import { useCallback, useEffect, useState } from "react";

import { copyToClipboard } from "@/lib/clipboard";

// Invite-only / hidden-login (owner, 2026-10-16) — the Referrals tab: every
// user's own invite link, how many clicks / signups each produced, and per-row
// copy + email buttons plus a send-to-everyone bulk action. Admin-only (the
// API enforces the session; this panel is inside the protected admin shell).

type Row = {
  id: string;
  email: string;
  createdAt: string;
  link: { code: string; clicks: number; conversions: number } | null;
  url: string | null;
  referredCount: number;
  referredBy: string | null;
  // Came-via as the referrer's email (resolved server-side); null when unknown.
  referredByEmail: string | null;
};

// Model C — a personalized invite: bound to one email, generated by the admin.
type Invite = {
  id: string;
  code: string;
  inviteeEmail: string;
  isActive: boolean;
  redeemedAt: string | null;
  createdAt: string;
  url: string;
};

export function ReferralsPanel() {
  const [rows, setRows] = useState<Row[] | null>(null);
  const [invites, setInvites] = useState<Invite[]>([]);
  const [busy, setBusy] = useState<string | null>(null);
  const [note, setNote] = useState<string | null>(null);
  const [inviteEmail, setInviteEmail] = useState("");
  // Came-via: which existing user this invite is attributed to when the invitee
  // signs up ("" = nobody — admin-only invite, not nested in the tree).
  const [inviteRef, setInviteRef] = useState("");

  const load = useCallback(async () => {
    const res = await fetch("/api/admin/referrals");
    if (!res.ok) {
      setRows([]);
      return;
    }
    const data = await res.json();
    setRows(data.rows ?? []);
    setInvites(data.invites ?? []);
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  // Model C — generate (or fetch the existing) invite for an email, optionally
  // emailing the link to the invitee.
  async function makeInvite(send: boolean) {
    const email = inviteEmail.trim();
    if (!email) return;
    setBusy(`__invite__`);
    setNote(null);
    try {
      const res = await fetch("/api/admin/referrals", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          action: "invite",
          email,
          send,
          referredByUserId: inviteRef || undefined,
        }),
      });
      const data = res.ok ? await res.json() : null;
      setNote(
        data
          ? send
            ? `Invite for ${data.invite.inviteeEmail} created and emailed.`
            : `Invite ready for ${data.invite.inviteeEmail} — copy the link below.`
          : `Failed to create invite (${res.status}).`,
      );
    } finally {
      setBusy(null);
      setInviteEmail("");
      void load();
    }
  }

  async function sendOne(userId: string, email: string) {
    setBusy(userId);
    setNote(null);
    try {
      const res = await fetch("/api/admin/referrals", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ action: "send", userId }),
      });
      setNote(
        res.ok
          ? `Invite link emailed to ${email}.`
          : `Failed to send to ${email} (${res.status}).`,
      );
    } finally {
      setBusy(null);
      void load();
    }
  }

  async function sendAll() {
    setBusy("__bulk__");
    setNote(null);
    try {
      const res = await fetch("/api/admin/referrals", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ action: "bulk" }),
      });
      const data = res.ok ? await res.json() : null;
      setNote(
        data
          ? `Sent ${data.sent}/${data.total} invite links.${
              data.failures?.length ? ` ${data.failures.length} failed.` : ""
            }`
          : "Bulk send failed.",
      );
    } finally {
      setBusy(null);
      void load();
    }
  }

  if (!rows) {
    return <p className="text-sm text-zinc-500">Loading referral tree…</p>;
  }

  return (
    <div className="flex flex-col gap-4">
      <div className="flex items-center justify-between gap-4">
        <div>
          <h2 className="text-lg font-semibold">Referrals</h2>
          <p className="text-sm text-zinc-500">
            Invite-only access: each user has one personal invite link. This is
            the tree of who came through whose link.
          </p>
        </div>
        <button
          type="button"
          onClick={sendAll}
          disabled={busy !== null}
          className="rounded-lg bg-zinc-900 px-4 py-2 text-sm font-semibold text-white disabled:opacity-50 dark:bg-zinc-50 dark:text-zinc-900"
        >
          {busy === "__bulk__" ? "Sending…" : "Email link to everyone"}
        </button>
      </div>

      {note && (
        <p className="rounded-lg bg-zinc-100 px-3 py-2 text-sm dark:bg-zinc-800">
          {note}
        </p>
      )}

      {/* Model C — invite a specific person by email: the strict gate for NEW users. */}
      <div className="rounded-xl border border-border p-4">
        <h3 className="text-sm font-semibold">Invite someone by email</h3>
        <p className="mt-1 text-xs text-zinc-500">
          New users can only sign up through an invite like this, and it works only for
          the exact email you enter. Use it for people who requested access via support.
        </p>
        <div className="mt-3 flex flex-wrap items-center gap-2">
          <input
            type="email"
            value={inviteEmail}
            onChange={(e) => setInviteEmail(e.target.value)}
            placeholder="invitee@example.com"
            className="min-w-[220px] flex-1 rounded-lg border border-border bg-bg px-3 py-2 text-sm"
          />
          {/* Came-via — attribute this invitee to an existing user at signup so
              they land under that user in the referral tree. */}
          <select
            value={inviteRef}
            onChange={(e) => setInviteRef(e.target.value)}
            title="Came via — which user this invitee is attributed to"
            className="max-w-[240px] rounded-lg border border-border bg-bg px-3 py-2 text-sm"
          >
            <option value="">Came via: nobody</option>
            {(rows ?? []).map((r) => (
              <option key={r.id} value={r.id}>
                {r.email}
              </option>
            ))}
          </select>
          <button
            type="button"
            onClick={() => void makeInvite(false)}
            disabled={busy !== null || !inviteEmail.trim()}
            className="rounded-lg border border-border px-3 py-2 text-sm disabled:opacity-40"
          >
            {busy === "__invite__" ? "Working…" : "Create link"}
          </button>
          <button
            type="button"
            onClick={() => void makeInvite(true)}
            disabled={busy !== null || !inviteEmail.trim()}
            className="rounded-lg bg-zinc-900 px-3 py-2 text-sm font-semibold text-white disabled:opacity-50 dark:bg-zinc-50 dark:text-zinc-900"
          >
            Create &amp; email
          </button>
        </div>
      </div>

      {invites.length > 0 && (
        <div className="overflow-x-auto rounded-xl border border-border">
          <table className="w-full text-sm">
            <thead>
              <tr className="border-b border-border bg-zinc-50 text-left text-xs uppercase text-zinc-500 dark:bg-zinc-900/50">
                <th className="px-3 py-2">Invitee</th>
                <th className="px-3 py-2">Status</th>
                <th className="px-3 py-2">Invite link</th>
                <th className="px-3 py-2">Created</th>
                <th className="px-3 py-2">Actions</th>
              </tr>
            </thead>
            <tbody>
              {invites.map((inv) => (
                <tr key={inv.id} className="border-b border-border last:border-0">
                  <td className="px-3 py-2 font-medium">{inv.inviteeEmail}</td>
                  <td className="px-3 py-2">
                    {inv.redeemedAt ? (
                      <span className="rounded bg-emerald-100 px-2 py-0.5 text-xs text-emerald-700 dark:bg-emerald-900/40 dark:text-emerald-300">
                        Redeemed {new Date(inv.redeemedAt).toLocaleDateString()}
                      </span>
                    ) : inv.isActive ? (
                      <span className="rounded bg-amber-100 px-2 py-0.5 text-xs text-amber-700 dark:bg-amber-900/40 dark:text-amber-300">
                        Pending
                      </span>
                    ) : (
                      <span className="rounded bg-zinc-100 px-2 py-0.5 text-xs text-zinc-500">
                        Revoked
                      </span>
                    )}
                  </td>
                  <td className="px-3 py-2 font-mono text-xs">{inv.url}</td>
                  <td className="px-3 py-2 text-zinc-500">
                    {new Date(inv.createdAt).toLocaleDateString()}
                  </td>
                  <td className="px-3 py-2">
                    <button
                      type="button"
                      onClick={() =>
                        void copyToClipboard(inv.url).then((ok) =>
                          setNote(
                            ok ? `Copied invite for ${inv.inviteeEmail}.` : "Copy failed.",
                          ),
                        )
                      }
                      className="rounded border border-border px-2 py-1 text-xs"
                    >
                      Copy
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      <div className="overflow-x-auto rounded-xl border border-border">
        <table className="w-full text-sm">
          <thead>
            <tr className="border-b border-border bg-zinc-50 text-left text-xs uppercase text-zinc-500 dark:bg-zinc-900/50">
              <th className="px-3 py-2">User</th>
              <th className="px-3 py-2">Joined</th>
              <th className="px-3 py-2">Invite link</th>
              <th className="px-3 py-2">Clicks</th>
              <th className="px-3 py-2">Signed up</th>
              <th className="px-3 py-2">Came via</th>
              <th className="px-3 py-2">Actions</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((r) => (
              <tr key={r.id} className="border-b border-border last:border-0">
                <td className="px-3 py-2 font-medium">{r.email}</td>
                <td className="px-3 py-2 text-zinc-500">
                  {new Date(r.createdAt).toLocaleDateString()}
                </td>
                <td className="px-3 py-2 font-mono text-xs">
                  {r.url ?? "—"}
                </td>
                <td className="px-3 py-2">{r.link?.clicks ?? 0}</td>
                <td className="px-3 py-2">{r.referredCount}</td>
                <td className="px-3 py-2 text-xs text-zinc-500">
                  {r.referredByEmail ?? r.referredBy ?? "—"}
                </td>
                <td className="px-3 py-2">
                  <div className="flex gap-2">
                    <button
                      type="button"
                      onClick={() =>
                        r.url &&
                        void copyToClipboard(r.url).then((ok) =>
                          setNote(ok ? `Copied ${r.email}'s link.` : "Copy failed."),
                        )
                      }
                      disabled={!r.url}
                      className="rounded border border-border px-2 py-1 text-xs disabled:opacity-40"
                    >
                      Copy
                    </button>
                    <button
                      type="button"
                      onClick={() => void sendOne(r.id, r.email)}
                      disabled={busy !== null}
                      className="rounded border border-border px-2 py-1 text-xs disabled:opacity-40"
                    >
                      {busy === r.id ? "Sending…" : "Email"}
                    </button>
                  </div>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}
